#!/usr/bin/env bash
set -euo pipefail

MY_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CALC="$MY_DIR/git-diff-label-calc.sh"

# The caller supplies and preflights the temporary directory; never fall back.
: "${TMPDIR:?TMPDIR must be configured for disposable Git fixtures}"
SCRATCH=$(mktemp -d "$TMPDIR/git-diff-label-test.XXXXXX")
trap 'rm -rf -- "$SCRATCH"' EXIT

commit_fixture() {
    git -C "$REPO" add -A
    git -C "$REPO" -c core.hooksPath=/dev/null -c commit.gpgsign=false \
        -c user.name='CI size fixture' -c user.email='ci-size-fixture@example.invalid' \
        commit -qm fixture
}

new_fixture() {
    REPO="$SCRATCH/$1"
    mkdir -p "$REPO/.github/workflows"
    git -c init.templateDir= init -q --initial-branch=main "$REPO"
    git -C "$REPO" config core.autocrlf false
    printf 'go.mod\ngo.sum\n' > "$REPO/.labelignore"
    printf 'module fixture\n' > "$REPO/go.mod"
    printf 'fixture checksum\n' > "$REPO/go.sum"
    printf 'package fixture\n' > "$REPO/source.go"
    printf 'package fixture\n' > "$REPO/harness.go"
    printf 'package fixture\n' > "$REPO/old_test.go"
    printf 'name: fixture\n' > "$REPO/.github/workflows/ci.yml"
    printf '// generated by fixture DO NOT EDIT\npackage fixture\n' > "$REPO/generated.go"
    printf '// Code generated by fixture DO NOT EDIT.\npackage fixture\n' > "$REPO/generated_test.go"
    commit_fixture
    BASE=$(git -C "$REPO" rev-parse HEAD)
    git -C "$REPO" update-ref refs/remotes/origin/main "$BASE"
}

lines() {
    awk -v count="$1" 'BEGIN { print "package fixture"; for (i=2; i<=count; i++) printf "// line %04d\n", i }' > "$REPO/$2"
}

finish_fixture() {
    commit_fixture
    git -C "$REPO" update-ref refs/remotes/pull/123/merge HEAD
    # Match pull_request_target: execute trusted scripts with the base checked out.
    git -C "$REPO" checkout -q --detach "$BASE"
}

CHECKS=0
check() {
    local name=$1 expected_rc=$2 label=$3 size=$4 fail_if_xl=${5:-1} rc=0
    local head_ref=${6-refs/remotes/pull/123/merge}
    (cd "$REPO" && MAIN_BRANCH=main DIFF_HEAD_REF="$head_ref" \
        FAIL_IF_XL="$fail_if_xl" DEBUG=0 "$CALC" --debug) \
        > "$SCRATCH/stdout" 2> "$SCRATCH/stderr" || rc=$?
    if [ "$rc" -ne "$expected_rc" ] || \
        ! grep -Fxq "TOTAL: $size" "$SCRATCH/stderr" || \
        ! grep -Fxq "LABEL: $label" "$SCRATCH/stderr"; then
        cat "$SCRATCH/stdout" "$SCRATCH/stderr" >&2
        echo "FAIL: $name (exit $rc, expected $expected_rc)" >&2
        exit 1
    fi
    if [ "$rc" -eq 0 ]; then
        [ "$(cat "$SCRATCH/stdout")" = "$label" ]
    else
        grep -Fq 'ERROR: This PR exceeds the maximum size of 500 lines.' "$SCRATCH/stdout"
    fi
    CHECKS=$((CHECKS + 1))
    echo "PASS: $name (exit $rc, $label, $size counted lines)"
}

# All existing classification boundaries, including the ordinary 500-line gate.
for entry in '20 size/xs' '21 size/s' '100 size/s' '101 size/m' '250 size/m' '251 size/l' '500 size/l' '501 size/xl'; do
    read -r count label <<< "$entry"
    new_fixture "production-$count"
    lines "$count" added.go
    finish_fixture
    rc=0
    if [ "$count" -gt 500 ]; then rc=1; fi
    check "production-$count" "$rc" "$label" "$count"
done
check classification-only-production 0 size/xl 501 0

new_fixture empty
git -C "$REPO" update-ref refs/remotes/pull/123/merge HEAD
check empty 0 size/xs 0

for count in 814 1000 1001; do
    new_fixture "test-only-$count"
    lines "$count" added_test.go
    finish_fixture
    rc=0
    if [ "$count" -gt 1000 ]; then rc=1; fi
    check "test-only-$count" "$rc" size/xl "$count"
done
check classification-only-test 0 size/xl 1001 0

# Mixed changes, including files omitted from the existing size calculation.
for path in source.go harness.go fixture.json .github/workflows/ci.yml go.mod go.sum generated.go; do
    new_fixture "mixed-${CHECKS}"
    lines 814 added_test.go
    printf '// changed\n' >> "$REPO/$path"
    finish_fixture
    size=815
    case "$path" in go.mod | go.sum | generated.go) size=814 ;; esac
    check "mixed-$path" 1 size/xl "$size"
done

for kind in whitespace blank deletion test-deletion test-rename production-rename type-change generated-test generated-marker-removal binary symlink; do
    new_fixture "$kind"
    lines 814 added_test.go
    size=814
    case "$kind" in
        whitespace) printf 'package  fixture\n' > "$REPO/source.go" ;;
        blank) printf '\n' >> "$REPO/source.go" ;;
        deletion) rm "$REPO/source.go" ;;
        test-deletion) rm "$REPO/old_test.go" ;;
        test-rename) mv "$REPO/old_test.go" "$REPO/renamed_test.go" ;;
        production-rename) mv "$REPO/source.go" "$REPO/renamed_test.go" ;;
        type-change) rm "$REPO/old_test.go"; ln -s source.go "$REPO/old_test.go"; size=816 ;;
        generated-test) printf '// changed\n' >> "$REPO/generated_test.go" ;;
        generated-marker-removal) printf 'package fixture\n' > "$REPO/generated_test.go" ;;
        binary) printf 'binary\0data\n' > "$REPO/binary_test.go" ;;
        symlink) ln -s old_test.go "$REPO/link_test.go"; size=815 ;;
    esac
    finish_fixture
    check "$kind" 1 size/xl "$size"
done

for path in 'space name_test.go' $'tab\t_test.go' $'newline\n_test.go' '冒_test.go' ':magic_test.go' '*glob_test.go'; do
    new_fixture "unusual-${CHECKS}"
    lines 814 "$path"
    finish_fixture
    check "unusual-${CHECKS}" 1 size/xl 814
done

new_fixture new-generated-test
printf '// Code generated by fixture DO NOT EDIT.\n' > "$REPO/added_test.go"
lines 814 body_test.go
finish_fixture
check new-generated-test 1 size/xl 815

new_fixture modified-tests
lines 813 added_test.go
printf '// changed\n' >> "$REPO/old_test.go"
finish_fixture
check modified-tests 0 size/xl 814

git -C "$REPO" checkout -q --detach refs/remotes/pull/123/merge
check default-head 0 size/xl 814 1 ''
git -C "$REPO" checkout -q --detach "$BASE"

# Errors while reading the complete diff or generated markers must fail closed.
mkdir "$SCRATCH/bin"
REAL_GIT=$(command -v git)
cat > "$SCRATCH/bin/git" <<'SH'
#!/usr/bin/env bash
set -eu
if [ "$GIT_FAILURE" = diff ]; then
    for arg in "$@"; do
        if [ "$arg" = --name-status ]; then exit 42; fi
    done
elif [ "$1" = grep ] && [ "${2:-}" = -q ]; then
    exit 2
fi
exec "$REAL_GIT" "$@"
SH
chmod +x "$SCRATCH/bin/git"
PATH="$SCRATCH/bin:$PATH" REAL_GIT="$REAL_GIT" GIT_FAILURE=diff check diff-read-failure 1 size/xl 814
PATH="$SCRATCH/bin:$PATH" REAL_GIT="$REAL_GIT" GIT_FAILURE=grep check generated-read-failure 1 size/xl 814
rm "$SCRATCH/bin/git"

# Actual wrapper, with only gh replaced: no real label reads or mutations.
cat > "$SCRATCH/bin/gh" <<'SH'
#!/usr/bin/env bash
set -eu
case "$1 $2" in
    'pr view') printf 'size/s\nsize/xl\n' ;;
    'pr edit') printf '%s\n' "$*" >> "$FAKE_GH_LOG" ;;
    *) exit 1 ;;
esac
SH
chmod +x "$SCRATCH/bin/gh"
(cd "$REPO" && PATH="$SCRATCH/bin:$PATH" FAKE_GH_LOG="$SCRATCH/gh-log" PR_NUMBER=123 \
    MAIN_BRANCH=main DIFF_HEAD_REF=refs/remotes/pull/123/merge FAIL_IF_XL=1 \
    "$MY_DIR/github-set-pr-label.sh") > "$SCRATCH/wrapper-out" 2> "$SCRATCH/wrapper-err"
printf 'pr edit 123 --remove-label size/s\npr edit 123 --add-label size/xl\n' > "$SCRATCH/expected-gh-log"
cmp "$SCRATCH/expected-gh-log" "$SCRATCH/gh-log"
[ ! -s "$SCRATCH/wrapper-out" ]
CHECKS=$((CHECKS + 1))
echo 'PASS: wrapper preserves size/xl labeling for bounded test-only changes'

new_fixture wrapper-production
lines 501 added.go
finish_fixture
rc=0
(cd "$REPO" && PATH="$SCRATCH/bin:$PATH" FAKE_GH_LOG="$SCRATCH/forbidden-gh-log" PR_NUMBER=123 \
    MAIN_BRANCH=main DIFF_HEAD_REF=refs/remotes/pull/123/merge FAIL_IF_XL=1 \
    "$MY_DIR/github-set-pr-label.sh") > "$SCRATCH/wrapper-out" 2> "$SCRATCH/wrapper-err" || rc=$?
[ "$rc" -eq 1 ]
[ ! -e "$SCRATCH/forbidden-gh-log" ]
CHECKS=$((CHECKS + 1))
echo 'PASS: wrapper rejects ordinary XL changes before gh calls'
echo "All $CHECKS deterministic fixture checks passed."

EXISTING_CHECKS=$CHECKS
if [ "$EXISTING_CHECKS" -ne 45 ]; then echo 'FAIL: historical case count' >&2; exit 1; fi
check_wrapper_failure() {
    local rc=0
    rm -f "$SCRATCH/rejected-gh-log"
    (cd "$REPO" && PATH="$SCRATCH/bin:$PATH" FAKE_GH_LOG="$SCRATCH/rejected-gh-log" PR_NUMBER=123 \
        MAIN_BRANCH=main DIFF_HEAD_REF=refs/remotes/pull/123/merge FAIL_IF_XL=1 \
        "$MY_DIR/github-set-pr-label.sh") > "$SCRATCH/wrapper-out" 2> "$SCRATCH/wrapper-err" || rc=$?
    if [ "$rc" -ne 1 ] || [ -e "$SCRATCH/rejected-gh-log" ]; then
        cat "$SCRATCH/wrapper-out" "$SCRATCH/wrapper-err" >&2
        echo "FAIL: wrapper $1 (exit $rc; expected exit 1 and no label edits)" >&2
        exit 1
    fi
    CHECKS=$((CHECKS + 1))
    echo "PASS: wrapper rejects $1 before label edits"
}

# Real committed blobs: late NUL, forced textual diff, invalid UTF-8 and controls.
for kind in late-nul separate-binary attribute-nul invalid-utf8 control c1-control utf8-text executable copy mixed-attributes working-text working-binary empty-added modified-whitespace modified-blank crlf no-final-newline; do
    new_fixture "$kind"
    if [ "$kind" = attribute-nul ]; then
        printf '*_test.go diff\n' > "$REPO/.gitattributes"
        commit_fixture
        BASE=$(git -C "$REPO" rev-parse HEAD)
        git -C "$REPO" update-ref refs/remotes/origin/main "$BASE"
    fi
    python3 - "$REPO" "$kind" <<'PY'
import pathlib, sys
repo, kind = pathlib.Path(sys.argv[1]), sys.argv[2]
data = bytearray(('package fixture\n' + ''.join('// padded line %04d\n' % i for i in range(814))).encode())
if kind in ('late-nul', 'working-text'):
    data[10599] = 0
elif kind == 'attribute-nul':
    data[30] = 0
elif kind == 'invalid-utf8':
    data[10599] = 255
elif kind == 'control':
    data[10599] = 1
elif kind == 'c1-control':
    data[10599:10601] = b'\xc2\x85'
else:
    data = ('package fixture\n' + '// 文本 café\n' * 813).encode()
if kind == 'empty-added': (repo / 'empty_test.go').write_bytes(b'')
if kind == 'modified-whitespace': (repo / 'old_test.go').write_bytes(b'package  fixture\n')
if kind == 'modified-blank': (repo / 'old_test.go').write_bytes(b'package fixture\n\n')
if kind == 'crlf': data = data.replace(b'\n', b'\r\n')
if kind == 'no-final-newline': data = data[:-1]
(repo / 'added_test.go').write_bytes(data)
if kind == 'separate-binary':
    binary = bytearray(b'//' + b'x' * 12000 + b'\n'); binary[10599] = 0
    (repo / 'binary_test.go').write_bytes(binary)
elif kind == 'copy':
    (repo / 'copied_test.go').write_bytes((repo / 'old_test.go').read_bytes())
elif kind == 'mixed-attributes':
    (repo / '.gitattributes').write_text('*_test.go diff\n')
PY
    if [ "$kind" = executable ]; then chmod +x "$REPO/added_test.go"; fi
    finish_fixture
    size=815 rc=1
    case "$kind" in
        utf8-text | executable | working-binary | empty-added | modified-whitespace | modified-blank | crlf | no-final-newline) size=814; rc=0 ;;
    esac
    # Neither a clean nor a binary unrelated working-tree copy may change eligibility.
    case "$kind" in
        working-text) printf 'package fixture\n' > "$REPO/added_test.go" ;;
        working-binary) printf 'binary\0copy\n' > "$REPO/added_test.go" ;;
    esac
    check "$kind" "$rc" size/xl "$size"
    if [ "$rc" -eq 1 ]; then check_wrapper_failure "$kind"; fi
done

new_fixture hidden-submodule
lines 814 added_test.go
finish_fixture
git -C "$REPO" checkout -q --detach refs/remotes/pull/123/merge
git -C "$REPO" update-index --add --cacheinfo "160000,$BASE,component_test.go"
git -C "$REPO" -c core.hooksPath=/dev/null -c commit.gpgsign=false \
    -c user.name='CI size fixture' -c user.email='ci-size-fixture@example.invalid' commit -qm fixture
git -C "$REPO" update-ref refs/remotes/pull/123/merge HEAD
git -C "$REPO" checkout -q --detach "$BASE"
git -C "$REPO" config diff.ignoreSubmodules all
check hidden-submodule 1 size/xl 814
check_wrapper_failure hidden-submodule

# Corrupt only qualification evidence; size counting and all other Git calls are real.
new_fixture malformed-evidence
lines 814 added_test.go
finish_fixture
cat > "$SCRATCH/bin/git" <<'PY'
